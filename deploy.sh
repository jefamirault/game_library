#!/usr/bin/env bash
#
# Push the code to Apps Script and update the live web app (same /exec URL),
# stamping what was deployed.
#
# Usage:
#   ./deploy.sh
set -euo pipefail
cd "$(dirname "$0")"

# The live /exec deployment (`clasp list-deployments` — the one pinned to a
# version, not @HEAD).
DEPLOYMENT_ID=AKfycbwa2wYGorgw98J3S_3U9WyUWEi6xiANAUiH36ewlKVHrh1oNBCwM3hZx3kK-IeQ3X-mvg
APP_URL="https://script.google.com/macros/s/${DEPLOYMENT_ID}/exec"

# ── Deploy stamp ─────────────────────────────────────────────────────────────
# Same deploy.json as the static sites, but Apps Script can't serve a loose
# .json file — clasp only pushes .gs/.html. So the stamp is baked into a
# generated src/DeployStamp.gs, and doGet serves it at <exec URL>/deploy.json.
# Degrades to no stamp outside a git checkout rather than failing the deploy.
if git rev-parse HEAD >/dev/null 2>&1; then
  DIRTY=false; git diff --quiet HEAD -- 2>/dev/null || DIRTY=true
  STAMP=$(printf '{"deployed_at":"%s","commit":"%s","branch":"%s","dirty":%s}' \
    "$(date -u +%FT%TZ)" "$(git rev-parse --short HEAD)" \
    "$(git rev-parse --abbrev-ref HEAD)" "$DIRTY")
  printf '// Generated by deploy.sh at deploy time. Do not edit or commit.\nvar DEPLOY_STAMP = %s;\n' \
    "$STAMP" > src/DeployStamp.gs
fi

clasp push -f
clasp redeploy "$DEPLOYMENT_ID"

echo "Done. → ${APP_URL}"
echo "Stamp: ${APP_URL}/deploy.json"
